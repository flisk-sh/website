// Builds the docs pages whose text lives in the Flisk CLI repository (flisk-sh/flisk, docs/*.md), so the site does
// not send readers to GitHub for them and the text is not kept by hand in two places. Edit the text at the source;
// this script, and a weekly job that opens the pull request, bring the pages in line.
//   node scripts/sync-docs.mjs               write the pages
//   node scripts/sync-docs.mjs --from <dir>  read the markdown from a local flisk docs/ folder instead of GitHub
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const RAW = "https://raw.githubusercontent.com/flisk-sh/flisk/main/docs/";
export const BLOB = "https://github.com/flisk-sh/flisk/blob/main/docs/";

export const PAGES = [
  {
    source: "cheat-sheet.md",
    out: "docs/cli/index.html",
    url: "/docs/cli/",
    title: "CLI commands",
    description: "Every flisk command, alias and flag on one page, with examples.",
    lead: "Every <code>flisk</code> command, alias and flag on one page. Your version may differ: run <code>flisk &lt;command&gt; --help</code> to check.",
  },
  {
    source: "troubleshooting.md",
    out: "docs/troubleshooting/index.html",
    url: "/docs/troubleshooting/",
    title: "Troubleshooting",
    description: "Flisk and Tilt error messages as they are printed, what causes each one and how to fix it.",
  },
];

const ALERTS = { NOTE: "Note", TIP: "Tip", IMPORTANT: "Important", WARNING: "Warning", CAUTION: "Caution" };

// A relative link in the source points into the Flisk repository; here it must be absolute, or one of our own pages.
export function resolveLink(href) {
  if (/^(https?:|mailto:|#|\/)/.test(href)) return href;
  const [path, hash = ""] = href.split("#");
  const own = PAGES.find((p) => p.source === path);
  if (own) return own.url + (hash ? `#${hash}` : "");
  const url = new URL(path, BLOB).href;
  return (path.endsWith("/") ? url.replace("/blob/", "/tree/") : url) + (hash ? `#${hash}` : "");
}

// The source is written for GitHub. This drops what the site's layout already gives (title, jump list), what its
// design rules ban (emoji, version labels) and what Jekyll cannot draw (mermaid, GitHub alerts).
export function toSiteMarkdown(source) {
  let text = source.replace(/\r\n/g, "\n");
  text = text.replace(/^# .*\n+/, "");
  text = text.replace(/^> .*\bv\d+\.\d+\.\d+\b.*\n+/, "");
  text = text.replace(/^(\*\*Jump to:\*\*|On this page:|Want the short version\?).*\n+/gm, "");
  text = text.replace(/```mermaid\n[\s\S]*?\n```\n+/g, "");
  text = text.replace(/^> \[!(\w+)\]\n> /gm, (_, kind) => `> **${ALERTS[kind] || "Note"}:** `);
  text = text.replace(/^(#{2,6}) (.*)$/gm, (_, hashes, title) => `${hashes} ${title.replace(/[\p{Extended_Pictographic}️]/gu, "").trim()}`);
  text = text.replace(/\]\(([^)\s]+)\)/g, (_, href) => `](${resolveLink(href)})`);
  return `${text.trim()}\n`;
}

// Refuses a source that would damage the page: an error page, or text that would end the raw block early.
export function sourceProblems(source) {
  const problems = [];
  if (/<html|<!doctype/i.test(source)) problems.push("looks like an HTML page");
  if (/\{%-?\s*endraw/.test(source)) problems.push("contains a Liquid endraw tag");
  if (!/^## /m.test(source)) problems.push("has no ## heading");
  if (source.length < 2000) problems.push(`is too short (${source.length})`);
  return problems;
}

export function renderPage(page, source) {
  return `---
layout: default
title: ${page.title} - Flisk CLI
description: "${page.description}"
---
{% comment %} Generated by scripts/sync-docs.mjs from ${BLOB}${page.source}. Do not edit here: change the source. {% endcomment %}
{% capture body %}{% raw %}
${toSiteMarkdown(source)}{% endraw %}{% endcapture %}
<div class="aw">
  <section class="aw-section aw-docs-section">
    <div class="aw-wrap aw-docs">
      {% include docs-sidebar.html %}

      <article class="aw-docs-body aw-docs-body--tight aw-docs-body--md">
        <h1>${page.title}</h1>
${page.lead ? `        <p class="aw-lead">${page.lead}</p>\n` : ""}{{ body | markdownify }}
      </article>
    </div>
  </section>
</div>
`;
}

export async function sync({ root, from, fetchText = async (url) => (await fetch(url)).text() }) {
  const written = [];
  for (const page of PAGES) {
    const source = from ? readFileSync(join(from, page.source), "utf8") : await fetchText(RAW + page.source);
    const problems = sourceProblems(source);
    if (problems.length) throw new Error(`${page.source} ${problems.join(", ")}`);
    const file = join(root, page.out);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, renderPage(page, source));
    written.push(page.out);
  }
  return written;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf("--from");
  const root = fileURLToPath(new URL("..", import.meta.url));
  const written = await sync({ root, from: at > 0 ? process.argv[at + 1] : undefined });
  console.log(`wrote ${written.join(", ")}`);
}
